"""Generate EXPERIMENTS.md -- the index of every registered experiment, grouped by model.

Reads the registry and emits a scannable map: model -> experiment -> command -> outputs ->
consuming notebook -> figures -> description, with the canonical experiment per model starred.
This doubles as the paper's reproducibility appendix and is the answer to "what experiments
exist and how do I run each one." Regenerate with ``python scripts/run.py index``.
"""
from __future__ import annotations

from src.repro.paths import ROOT
from experiments.registry import MODELS, by_model


def write_index():
    grouped = by_model()
    lines = [
        "# Experiments",
        "",
        "Every paper experiment, runnable through one entry point:",
        "",
        "```",
        "python scripts/run.py list                 # this table",
        "python scripts/run.py run <name>           # run one experiment (with provenance)",
        "python scripts/run.py run-all [--model M]  # run all / one model",
        "```",
        "",
        "Grouped by **model** -- phlogiston and cosmology are the two co-equal main models "
        "(phlogiston's canonical reference is `multiagent_topology`); `landscape` is a "
        "cosmology-adjacent group. Each run writes `results/<out_dir>/` containing "
        "`simulation_arrays.npz`, `summary.json`, the diagnostic figures, and a `manifest.json` "
        "recording the git SHA, environment, seeds, resolved params, and per-array hashes -- so "
        "any figure traces back to the exact code and configuration that produced it.",
        "",
        "_Auto-generated by `python scripts/run.py index`; do not edit by hand._",
        "",
    ]
    for model in MODELS:
        specs = grouped.get(model, [])
        if not specs:
            continue
        lines.append(f"## {model}")
        lines.append("")
        for s in specs:
            star = "  ⭐ _(canonical)_" if s.canonical else ""
            lines.append(f"### `{s.name}`{star}")
            lines.append("")
            lines.append(s.description)
            lines.append("")
            lines.append(f"- **Run:** `python scripts/run.py run {s.name}`")
            lines.append(f"- **Outputs:** `results/{s.out_dir}/`")
            nb = s.consumes.get("notebook")
            if nb:
                lines.append(f"- **Notebook:** `{nb}`")
            figs = s.consumes.get("figures")
            if figs:
                lines.append(f"- **Figures:** {', '.join(figs)}")
            if s.seeds:
                lines.append(f"- **Seeds:** {list(s.seeds)}")
            lines.append("")
    path = ROOT / "EXPERIMENTS.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
